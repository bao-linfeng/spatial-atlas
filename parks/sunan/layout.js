// 风车式独栋：西区 4×5、中区 2×5、东区 2×5，去掉会所占位（rows / cols 为网格坐标，w / d 米）
const rows = [-16, 42, 92, 172, 236];
const villaCols = [
  { cols: [-261, -185, -109, -33], w: 24, d: 20 },
  { cols: [85, 160], w: 24, d: 20 },
  { cols: [230, 286], w: 21, d: 19 },
];
export const VILLAS = [];
{
  let n = 1;
  villaCols.forEach((blk, bi) => {
    rows.forEach((v, ri) => {
      blk.cols.forEach((u, ci) => {
        if (bi === 0 && ri === 4 && ci >= 2) return; // 会所
        // 风车式：2×2 为一组，四栋各自错位并交替转 90°
        const k = (ri % 2) * 2 + (ci % 2);
        const off = [[5, -4], [4, 5], [-4, -5], [-5, 4]][k];
        const turn = (k === 1 || k === 2) && bi !== 2;
        VILLAS.push({
          id: `V${String(n).padStart(2, '0')}`, pos: G(u + off[0], v + off[1]),
          w: turn ? blk.d : blk.w, d: turn ? blk.w : blk.d,
          f: [4, 5, 5, 6, 4][(ri + ci + bi) % 5],
          court: k % 2 === 0,
        });
        n++;
      });
    });
  });
}

